interface Ring {
  points: readonly number[];
  minLon: number;
  maxLon: number;
  minLat: number;
  maxLat: number;
}

const rings: Ring[] = RINGS.map((points) => {
  let minLon = Infinity;
  let maxLon = -Infinity;
  let minLat = Infinity;
  let maxLat = -Infinity;
  for (let i = 0; i < points.length; i += 2) {
    const lon = points[i] as number;
    const lat = points[i + 1] as number;
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  }
  return { points, minLon, maxLon, minLat, maxLat };
});

function inRing(ring: Ring, lon: number, lat: number): boolean {
  if (lon < ring.minLon || lon > ring.maxLon || lat < ring.minLat || lat > ring.maxLat) return false;
  const p = ring.points;
  let inside = false;
  for (let i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    const xi = p[i] as number;
    const yi = p[i + 1] as number;
    const xj = p[j] as number;
    const yj = p[j + 1] as number;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** True when (lon, lat) in degrees falls on land in the coarse outline (Antarctica below -68°). */
export function isLand(lon: number, lat: number): boolean {
  if (lat <= -68) return true;
  let inside = false;
  for (const ring of rings) if (inRing(ring, lon, lat)) inside = !inside;
  return inside;
}
