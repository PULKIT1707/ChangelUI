/** The item's primary tag within its category, or "More" when it has none (or a foreign one). */
export function tagOf(category: Category, slug: string): string {
  const tag = TAG_OF[slug];
  return tag !== undefined && CATEGORY_TAGS[category].includes(tag) ? tag : OTHER_TAG;
}

/** URL-safe tag id: "Pointer & layout" -> "pointer-layout". */
export function tagSlug(tag: string): string {
  return tag
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** Groups items by tag in CATEGORY_TAGS order; empty tags are dropped, "More" goes last. */
export function groupByTag<T extends { category: Category; slug: string }>(
  category: Category,
  items: readonly T[],
): { tag: string; items: T[] }[] {
  const order = [...CATEGORY_TAGS[category], OTHER_TAG];
  return order
    .map((tag) => ({ tag, items: items.filter((item) => tagOf(category, item.slug) === tag) }))
    .filter((group) => group.items.length > 0);
}

