function component(name: string, title: string): Entry {
  return { name, title, category: "components", file: `src/components/${name}.tsx`, client: true, docs: true };
}

function item(category: "text" | "effects" | "backgrounds" | "charts", name: string, title: string): Entry {
  return { name, title, category, file: `src/${category}/${name}.tsx`, client: true, docs: true };
}

function hook(name: string, title: string): Entry {
  return { name, title, category: "hooks", file: `src/hooks/${name}.ts`, client: true, docs: true };
}
