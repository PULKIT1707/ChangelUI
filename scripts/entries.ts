// Single source of truth for the library's public entries (design 5.3).
// tsup, sync-exports, the invariant tests and the dashboard registry checks all read this list.
// Plain erasable TypeScript: Node 24 runs it directly.

export type Category = "components" | "text" | "effects" | "backgrounds" | "charts" | "hooks";

export interface Entry {
  /** kebab-case; equals the file basename, the package subpath and the dashboard slug */
  name: string;
  /** display name ("Button", "useMediaQuery", "cn") */
  title: string;
  category: Category;
  /** repo-relative source file, e.g. "src/components/button.tsx" */
  file: string;
  /** false only for "cn", "motion-presets", "theme-builder", "chart-scales" and "theme-script" (server-safe, no "use client") */
  client: boolean;
  /** false only for "theme-script" (documented on the ThemeToggle page) */
  docs: boolean;
}

